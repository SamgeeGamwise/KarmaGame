namespace Engine.Input;

/// <summary>
/// Mouse button identifiers for action bindings.
/// </summary>
public enum MouseButton
{
    /// <summary>
    /// Left mouse button.
    /// </summary>
    Left = 0,

    /// <summary>
    /// Right mouse button.
    /// </summary>
    Right = 1,

    /// <summary>
    /// Middle mouse button.
    /// </summary>
    Middle = 2,

    /// <summary>
    /// XButton1 mouse button.
    /// </summary>
    XButton1 = 3,

    /// <summary>
    /// XButton2 mouse button.
    /// </summary>
    XButton2 = 4
}
